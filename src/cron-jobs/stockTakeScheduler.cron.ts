import cron from "node-cron";
import { InventoryStockTakeScheduleModel } from "models/Inventory/Inventorystocktakeschedule.model";
import { InventoryStockTakeModel } from "models/Inventory/Inventorystocktake.model";
import {
  sendNotification,
  getIdsFromPermissions,
} from "../util/sendNotification.util";
import { allPermissions } from "../types/Permissions.type";
import { EmployeeModel } from "../models/HR/Employee.model";
import { NotificationType } from "../models/Notifications/Notification.model";

// ─── stockTakeSchedulerJob ────────────────────────────────────────────────────
// Runs every day at 06:00.
// Checks all active InventoryStockTakeSchedule records.
// For each schedule where nextDueAt is today or past:
//   1. Creates a new scheduled InventoryStockTake document
//   2. Sends a banner notification to the store manager of that location
//   3. If daysOverdue > gracePeriodDays, escalates to hotel manager too

export const stockTakeSchedulerJob = () => {
  cron.schedule("0 6 * * *", async () => {
    console.log("🔄 Running stock take scheduler job...");

    try {
      const now = new Date();

      // Find all active schedules that are due or overdue
      const dueSchedules = await InventoryStockTakeScheduleModel.find({
        isActive: true,
        nextDueAt: { $lte: now },
      })
        .populate("location", "name code")
        .lean();

      if (dueSchedules.length === 0) {
        console.log("✅ No stock takes due today.");
        return;
      }

      console.log(
        `📋 Found ${dueSchedules.length} due stock take schedule(s).`
      );

      // Get hotel manager IDs for escalation
      const managerIds = await getIdsFromPermissions(
        allPermissions.inventoryStockTakes.approve
      );

      for (const schedule of dueSchedules) {
        const locationName =
          (schedule.location as any)?.name ?? "Unknown Location";
        const locationCode = (schedule.location as any)?.code ?? "";

        const daysOverdue = Math.floor(
          (now.getTime() - new Date(schedule.nextDueAt!).getTime()) /
            (1000 * 60 * 60 * 24)
        );

        // Check if a stock take for this location is already in progress
        // to avoid creating duplicates if the job runs multiple times
        const existingActiveStockTake = await InventoryStockTakeModel.findOne({
          location: schedule.location,
          status: { $in: ["scheduled", "in_progress", "pending_approval"] },
        });

        if (existingActiveStockTake) {
          console.log(
            `ℹ️  Stock take already active for ${locationName}. Skipping creation.`
          );

          // Still send escalation if overdue and grace period exceeded
          if (daysOverdue > schedule.gracePeriodDays && managerIds.length > 0) {
            const escalationTitle = `⚠️ Stock Take Overdue: ${locationName}`;
            const escalationMessage = `The stock take for ${locationName} (${locationCode}) is ${daysOverdue} day(s) overdue. It was created but the store manager has not started counting. Grace period of ${schedule.gracePeriodDays} day(s) has been exceeded.`;

            await sendNotification({
              userIds: managerIds,
              title: escalationTitle,
              message: escalationMessage,
              type: NotificationType.INVENTORY_CRON_ERROR,
              entityRef: {
                model: "InventoryStockTake",
                id: String(existingActiveStockTake._id),
              },
              redirectUrl: `/inventory/stock-takes/${existingActiveStockTake._id}`,
            });
          }

          continue;
        }

        // Find a system user to set as initiatedBy
        // Use the first hotel manager available
        const systemUserId = managerIds[0] ?? null;

        if (!systemUserId) {
          console.error(
            `❌ No hotel manager found to initiate stock take for ${locationName}. Skipping.`
          );
          continue;
        }

        // Create the stock take document
        const stockTake = await InventoryStockTakeModel.create({
          location: schedule.location,
          scope: schedule.scope,
          scopeCategory: schedule.scopeCategory ?? undefined,
          status: "scheduled",
          scheduledFor: now,
          isScheduled: true,
          initiatedBy: systemUserId,
          notes: `Auto-generated by stock take schedule. ${
            daysOverdue > 0 ? `${daysOverdue} day(s) overdue.` : ""
          }`,
        });

        console.log(
          `✅ Created stock take ${stockTake.stockTakeNumber} for ${locationName}.`
        );

        // Find the store manager(s) assigned to this location
        // via Employee.defaultInventoryLocation
        const storeManagerEmployees = await EmployeeModel.find({
          defaultInventoryLocation: schedule.location,
        })
          .select("user")
          .lean();

        const storeManagerUserIds = storeManagerEmployees.map((e) =>
          e.user.toString()
        );

        const storeManagerTitle = `📋 Stock Take Due: ${locationName}`;
        const storeManagerMessage =
          daysOverdue > 0
            ? `A stock take for ${locationName} (${locationCode}) is ${daysOverdue} day(s) overdue. Stock take ${stockTake.stockTakeNumber} has been created and is ready for you to start counting. Please begin the count as soon as possible.`
            : `A scheduled stock take for ${locationName} (${locationCode}) is due today. Stock take ${stockTake.stockTakeNumber} has been created and is ready for you to start counting.`;

        // Notify store managers
        if (storeManagerUserIds.length > 0) {
          await sendNotification({
            userIds: storeManagerUserIds,
            title: storeManagerTitle,
            message: storeManagerMessage,
            type:
              daysOverdue > 0
                ? NotificationType.INVENTORY_WARNING
                : NotificationType.INFO,
            entityRef: {
              model: "InventoryStockTake",
              id: String(stockTake._id),
            },
            redirectUrl: `/inventory/stock-takes/${stockTake._id}`,
          });
        }

        // Escalate to hotel manager if grace period exceeded
        if (daysOverdue > schedule.gracePeriodDays && managerIds.length > 0) {
          const escalationTitle = `🔴 Stock Take Overdue: ${locationName}`;
          const escalationMessage = `The scheduled stock take for ${locationName} (${locationCode}) is ${daysOverdue} day(s) overdue. The grace period of ${schedule.gracePeriodDays} day(s) has been exceeded. Stock take ${stockTake.stockTakeNumber} has been created. Please follow up with the store manager.`;

          await sendNotification({
            userIds: managerIds,
            title: escalationTitle,
            message: escalationMessage,
            type: NotificationType.INVENTORY_CRON_ERROR,
            entityRef: {
              model: "InventoryStockTake",
              id: String(stockTake._id),
            },
            redirectUrl: `/inventory/stock-takes/${stockTake._id}`,
          });
        }
      }

      console.log("✅ Stock take scheduler job complete.");
    } catch (err) {
      console.error("❌ stockTakeSchedulerJob error:", err);
    }
  });
};
